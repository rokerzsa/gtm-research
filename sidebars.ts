import type {SidebarsConfig} from '@docusaurus/plugin-content-docs';
import {researchBooks, bookDocId, type Chapter, type ResearchBook} from './src/data/researchLibrary';

type ChapterItem = string | {
  type: 'category';
  label: string;
  link?: {type: 'doc'; id: string};
  items: ChapterItem[];
};

function chapterItem(book: ResearchBook, chapter: Chapter): ChapterItem {
  if (typeof chapter === 'string') return bookDocId(book, chapter);
  return {
    type: 'category',
    label: chapter.label,
    ...(chapter.index ? {link: {type: 'doc' as const, id: bookDocId(book, chapter.index)}} : {}),
    items: chapter.chapters.map((item) => chapterItem(book, item)),
  };
}

// Each company owns its sidebar association and pagination sequence.
// A flat autogenerated slice here would lift chapters out of their company root.
const sidebars: SidebarsConfig = Object.fromEntries(researchBooks.map((book) => [
  book.sidebarId,
  [
    {type: 'link', label: '← Research library', href: '/'},
    {
      type: 'category',
      label: book.label,
      collapsed: false,
      link: {type: 'doc', id: bookDocId(book, 'index')},
      items: [
        ...book.chapters.map((chapter) => chapterItem(book, chapter)),
        ...(book.supplemental?.length ? [{
          type: 'category' as const,
          label: 'Additional reading guides',
          items: book.supplemental.map((path) => ({type: 'ref' as const, id: bookDocId(book, path)})),
        }] : []),
      ],
    },
  ],
]));

export default sidebars;
